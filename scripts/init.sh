#!/usr/bin/env sh
# First-run secret generation for Arya.
#
# The repo ships NO working credentials (they'd be public). This script
# generates them locally, once, into files git ignores:
#
#   .env                  - secrets docker-compose interpolates
#   livekit.yaml          - LiveKit server config (key/secret must match .env)
#   seaweedfs-s3.json     - SeaweedFS S3 identities (must match .env)
#   backend/.env.local    - same values with localhost URLs, for running the
#                           API/worker from source (uvicorn / agent.py dev)
#
# Idempotent: existing files are never overwritten — values are read back
# from .env so a partial state (e.g. livekit.yaml deleted) regenerates
# consistently. Rotating for real = delete the files and re-run, then
# ALTER the postgres user's password (the pg volume keeps the old one):
#   docker compose exec postgres psql -U arya -d arya \
#     -c "ALTER USER arya WITH PASSWORD '<new>';"

set -eu
cd "$(dirname "$0")/.."

rand() { openssl rand -hex "$1"; }

# ── resolve values: existing .env wins, otherwise generate ─────────────────
if [ -f .env ]; then
  # shellcheck disable=SC1091
  . ./.env
fi
LIVEKIT_API_KEY="${LIVEKIT_API_KEY:-arya-$(rand 4)}"
LIVEKIT_API_SECRET="${LIVEKIT_API_SECRET:-$(openssl rand -base64 32)}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-$(rand 16)}"
S3_ACCESS_KEY="${S3_ACCESS_KEY:-arya-$(rand 4)}"
S3_SECRET_KEY="${S3_SECRET_KEY:-$(rand 16)}"
# Signs widget visitor tokens (backend/src/visitors.py). Rotating it makes
# every widget visitor a new person; their old memories stay in Mem0 but
# are no longer reachable.
ARYA_VISITOR_SECRET="${ARYA_VISITOR_SECRET:-$(rand 32)}"
# Shared by the api and arya-whatsapp: proves a session request comes from
# the bridge and may name a WhatsApp customer.
ARYA_BRIDGE_TOKEN="${ARYA_BRIDGE_TOKEN:-$(rand 24)}"

# Appends one KEY=value line to a file when the key is absent. How secrets
# added after a machine's first init reach an existing .env without
# touching any value already there.
ensure_line() { # file key value
  if ! grep -q "^$2=" "$1"; then
    # A hand-edited file may lack its final newline; appending straight
    # after it would glue the new key onto the last line.
    [ -n "$(tail -c1 "$1")" ] && echo >> "$1"
    printf '%s=%s\n' "$2" "$3" >> "$1"
    echo "added $2 to $1"
  fi
}

if [ ! -f .env ]; then
  cat > .env <<EOF
# Generated by scripts/init.sh — gitignored, one per machine.
# Rotation: see the header of scripts/init.sh.
LIVEKIT_API_KEY=$LIVEKIT_API_KEY
LIVEKIT_API_SECRET=$LIVEKIT_API_SECRET
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
S3_ACCESS_KEY=$S3_ACCESS_KEY
S3_SECRET_KEY=$S3_SECRET_KEY
ARYA_VISITOR_SECRET=$ARYA_VISITOR_SECRET
ARYA_BRIDGE_TOKEN=$ARYA_BRIDGE_TOKEN
EOF
  echo "wrote .env"
else
  echo ".env exists — kept"
  ensure_line .env ARYA_VISITOR_SECRET "$ARYA_VISITOR_SECRET"
  ensure_line .env ARYA_BRIDGE_TOKEN "$ARYA_BRIDGE_TOKEN"
fi

if [ ! -f livekit.yaml ]; then
  cat > livekit.yaml <<EOF
# Generated by scripts/init.sh — gitignored. keys must match .env.
port: 7880
rtc:
  tcp_port: 7881
  port_range_start: 50000
  port_range_end: 50100
  use_external_ip: false
keys:
  $LIVEKIT_API_KEY: $LIVEKIT_API_SECRET
logging:
  level: info
EOF
  echo "wrote livekit.yaml"
else
  echo "livekit.yaml exists — kept"
fi

if [ ! -f seaweedfs-s3.json ]; then
  cat > seaweedfs-s3.json <<EOF
{
  "identities": [
    {
      "name": "arya",
      "credentials": [
        {
          "accessKey": "$S3_ACCESS_KEY",
          "secretKey": "$S3_SECRET_KEY"
        }
      ],
      "actions": ["Admin", "Read", "Write", "List", "Tagging"]
    }
  ]
}
EOF
  echo "wrote seaweedfs-s3.json"
else
  echo "seaweedfs-s3.json exists — kept"
fi

if [ ! -f backend/.env.local ]; then
  cat > backend/.env.local <<EOF
# Generated by scripts/init.sh — gitignored. For running the API/worker
# from SOURCE on the host (docker services get these from compose):
#   cd backend && uv run uvicorn api:app --app-dir src --port 8000
#   cd backend && uv run python src/agent.py dev
LIVEKIT_URL=ws://localhost:7880
LIVEKIT_API_KEY=$LIVEKIT_API_KEY
LIVEKIT_API_SECRET=$LIVEKIT_API_SECRET
DATABASE_URL=postgresql://arya:$POSTGRES_PASSWORD@localhost:5432/arya
S3_ENDPOINT=localhost:8333
S3_ACCESS_KEY=$S3_ACCESS_KEY
S3_SECRET_KEY=$S3_SECRET_KEY
ARYA_VISITOR_SECRET=$ARYA_VISITOR_SECRET
ARYA_BRIDGE_TOKEN=$ARYA_BRIDGE_TOKEN
EOF
  echo "wrote backend/.env.local"
else
  echo "backend/.env.local exists — kept"
  ensure_line backend/.env.local ARYA_VISITOR_SECRET "$ARYA_VISITOR_SECRET"
  ensure_line backend/.env.local ARYA_BRIDGE_TOKEN "$ARYA_BRIDGE_TOKEN"
fi

echo "done — run: docker compose up -d --build"
